#!/usr/bin/env python
"""Generate out/REPORT.md: the audit's findings, in one readable file.

The release list promises a reproducible report. The paper is four pages and
cannot carry every number; this is the artefact a curator actually reads before
deciding whether to act, and it is generated from `out/analysis/*.json` so it can
never drift from the measurements.

Everything here is derived. Nothing is written by hand, and nothing asserts a human
judgment that does not exist: precision reads "not yet collected" until labels do.
"""

from __future__ import annotations

import datetime
import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
AN = REPO / "out" / "analysis"
OUT = REPO / "out" / "REPORT.md"


def load(name: str):
    p = AN / name
    return json.load(open(p)) if p.exists() else None


def pct(x, digits: int = 3) -> str:
    return "--" if x is None else f"{x * 100:.{digits}f}%"


def main() -> int:
    s = load("summary.json")
    if not s:
        print("run scripts/analyze.py first", file=sys.stderr)
        return 1
    suite = load("testsuite_report.json") or {}
    patch = load("patch_report.json") or {}
    effect = load("patch_effect.json") or {}
    temporal = load("temporal_stability.json") or {}
    xlang = load("cross_language.json") or {}
    heldout = load("heldout_comparison.json") or []
    replay = load("replay_report.json") or {}
    cost = load("classification_cost.json") or {}
    clustering = load("sample_clustering.json") or {}

    agent = [f for f in s["findings"] if f["source"] == "agent"]
    n_labels = s.get("n_human_labels", 0)
    L: list[str] = []
    w = L.append

    w("# Audit report: the Slovak portion of FineWeb2")
    w("")
    w(f"Generated by `scripts/make_report.py` on "
      f"{datetime.date.today().isoformat()} from the artefacts in `out/analysis/`. "
      "Do not edit by hand; re-run it instead.")
    w("")
    w("## What was audited")
    w("")
    n_total = suite.get("n_total")
    w(f"* Corpus: `ivykopal/fineweb2-slovak`, "
      f"{n_total:,} documents" if n_total else "* Corpus: `ivykopal/fineweb2-slovak`")
    if temporal:
        w(f"* {temporal['crawls']} Common Crawl snapshots, "
          f"{temporal.get('first', '?')} to {temporal.get('last', '?')}")
    ins = s.get("agent_inspections", {})
    if ins:
        used = ", ".join(f"{k}: {v}" for k, v in ins.items() if v is not None)
        w(f"* Agent runs and inspections used: {used}")
    w(f"* Agent cost: ${s.get('agent_cost_usd', 0):.2f} in total")
    w(f"* Human labels collected so far: {n_labels}"
      + ("" if n_labels else " — every precision below therefore reads `not yet collected`"))
    w("")

    w("## Findings")
    w("")
    w("| finding | phenomenon | prevalence | documents | largest static-slice overlap "
      "| human precision | status |")
    w("|---|---|---|---|---|---|---|")
    for f in sorted(agent, key=lambda f: -f["prevalence"]):
        h = f.get("human") or {}
        prec = ("not yet collected" if not h.get("n_judged")
                else f"{h['precision']:.2f} "
                     f"[{h['precision_ci95'][0]:.2f},{h['precision_ci95'][1]:.2f}] "
                     f"(n={h['n_judged']})")
        ov = f.get("max_baseline_overlap")
        w(f"| `{f['id']}` | {f.get('adjudication_group') or '--'} "
          f"| {pct(f['prevalence'], 4)} | {f['n_matched']:,} | {pct(ov, 1)} "
          f"| {prec} | {f.get('human_decision', 'pending')} |")
    w("")
    for f in sorted(agent, key=lambda f: -f["prevalence"]):
        w(f"### `{f['id']}`")
        w("")
        w(f"**Selector.** `{f['selector']}`")
        w("")
        w(f"**Description.** {' '.join(str(f['description']).split())}")
        w("")
        if f.get("agent_evidence"):
            w(f"**Evidence the auditor gathered.** {' '.join(str(f['agent_evidence']).split())}")
            w("")
        if f.get("likely_false_positives"):
            w(f"**Likely false positives.** "
              f"{' '.join(str(f['likely_false_positives']).split())}")
            w("")
        if f.get("agent_example_ids"):
            w("**Documents to start from.** "
              + ", ".join(f"`{i}`" for i in f["agent_example_ids"]))
            w("")
        ovl = f.get("baseline_overlap") or {}
        if ovl:
            w("**Overlap with the obvious static slices.** "
              + ", ".join(f"{k} {pct(v, 1)}" for k, v in ovl.items()))
            w("")
        if f.get("rediscovered_by"):
            w(f"**Independently proposed by.** {', '.join(f['rediscovered_by'])}")
            w("")

    w("## The tests")
    w("")
    if suite.get("tests"):
        w("| test | kind | status | prevalence | documents |")
        w("|---|---|---|---|---|")
        for t in suite["tests"]:
            w(f"| `{t['id']}` | {t.get('kind', '')} | **{t['status']}** "
              f"| {pct(t['prevalence'], 4)} | {t['n_matched']:,} |")
        w("")
        fails = [t["id"] for t in suite["tests"] if t["status"] == "FAIL"]
        w(f"{len(suite['tests'])} tests over {suite.get('n_total', 0):,} documents in "
          f"{suite.get('seconds', 0)}s, no GPU and no model calls. "
          + (f"Failing: {', '.join(f'`{x}`' for x in fails)} — a failing test is a live "
             "defect, not a broken harness." if fails else "All passing."))
        w("")

    if effect:
        w("## Applying the findings as patches")
        w("")
        w(f"* Removing every patched slice keeps "
          f"{effect['documents_kept'] * 100:.2f}% of documents.")
        w(f"* Each patched guard then matches nothing: "
          f"{', '.join('`' + x + '`' for x in effect['fixed'])}.")
        w(f"* Still failing by design (a filter cannot fix these): "
          f"{', '.join('`' + x + '`' for x in effect['failing_after'])}.")
        if patch.get("combined"):
            c = patch["combined"]
            w(f"* Drop list: {c['documents_removed']:,} documents "
              f"({c['document_share'] * 100:.2f}%) and {c['word_share'] * 100:.2f}% of words.")
        w("")

    if temporal.get("tests"):
        w("## Do the guards still fire on recent crawls?")
        w("")
        w("| test | all | older | newest 8 | crawls present | peak |")
        w("|---|---|---|---|---|---|")
        for t in sorted(temporal["tests"], key=lambda t: -t["share_all"]):
            w(f"| `{t['id']}` | {pct(t['share_all'])} | {pct(t['share_older'])} "
              f"| {pct(t['share_recent'])} | {t['crawls_present']}/{t['crawls_total']} "
              f"| {t['peak_crawl']} at {pct(t['peak_share'], 1)} |")
        w("")

    if xlang:
        w("## The same suite on other languages")
        w("")
        w(f"* Invalid confidence holds in {xlang['configs_with_defect']} of "
          f"{xlang['configs']} upstream FineWeb2 configurations, across "
          f"{len(xlang['scripts'])} scripts "
          f"({xlang['share_min'] * 100:.1f}%–{xlang['share_max'] * 100:.1f}% of documents), "
          f"every one bounded by {xlang['max_score_overall']:.5f}.")
        if xlang.get("clean_configs"):
            w(f"* Clean configurations: {', '.join(xlang['clean_configs'])}.")
        w("* On foreign corpora the Slovak tests report themselves out of scope, and on "
          "a release that ships fewer columns the affected tests report themselves "
          "unmeasurable rather than passing vacuously.")
        w("")

    if heldout:
        g = [r for r in heldout if r["ratio"] and r["id"] != "document_ids_unique"]
        if g:
            w(f"* On the corpus's held-out split every slice guard transfers within "
              f"{min(r['ratio'] for r in g):.2f}–{max(r['ratio'] for r in g):.2f}× its "
              f"training-split prevalence.")
            w("")

    w("## Cost and reproducibility")
    w("")
    if cost:
        w(f"* Classifying every document with an LLM instead, measured on a sample: "
          f"${cost['usd_per_1000_documents']:.2f} per thousand documents, i.e. "
          f"${cost['extrapolated_usd_full_corpus']:,.0f} per pass — against "
          f"${s.get('agent_cost_usd', 0):.2f} for the audit.")
    if replay:
        w(f"* Trajectory replay: {replay['matched_as_set']}/{replay['replayed']} calls "
          f"return the same rows ({replay['set_rate'] * 100:.1f}%) and "
          f"{replay['matched_exactly']} are identical byte for byte in this run. Both "
          "counts move by a call or two between repeats, because a query whose ordering "
          "key ties at the LIMIT cutoff returns a different tied subset per scan; at most "
          f"{replay['replayed'] - replay['matched_as_set']} calls differ, and none raises.")
    if clustering.get("agent_min_hosts_in_sample") is not None:
        w(f"* Each validation sample of 25 documents spans at least "
          f"{clustering['agent_min_hosts_in_sample']} distinct hosts, largest single host "
          f"{clustering['agent_max_top_host_share'] * 100:.0f}%, so the precision "
          "intervals are close to the independent-draw case rather than optimistic.")
    w("* `scripts/reproduce.sh` runs the whole pipeline.")
    w("")
    w("## What still needs a person")
    w("")
    if not n_labels:
        w("* The blinded annotation package is prepared but not yet labelled "
          "(`scripts/annotate.py`).")
    n_dec = s.get("n_adjudicated_groups", 0)
    w(f"* Finding adjudication: {n_dec} of "
      f"{len({f.get('adjudication_group') for f in s['findings'] if f.get('adjudication_group')})} "
      "groups decided (`out/adjudication/decisions.csv`).")
    w("* Nothing in this report is a model's judgment standing in for a person's.")
    w("")

    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT.relative_to(REPO)} ({len(L)} lines, "
          f"{OUT.stat().st_size / 1024:.1f} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
