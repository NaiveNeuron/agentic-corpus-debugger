#!/usr/bin/env python
"""Build the blinded human-validation package.

Draws a fixed number of fresh documents from each candidate slice (agent
findings and baseline findings) plus a random control sample, excluding every
document any agent run already inspected, shuffles them, and writes:

  out/annotation/items.csv        item_id, text  (all the annotator sees)
  out/annotation/provenance.csv   item_id -> doc_id, slice, source (held back)
  out/annotation/GUIDELINES.md    label definitions

Slices with identical selectors are merged, so that a phenomenon rediscovered
by several runs is validated once.
"""

from __future__ import annotations

import argparse
import csv
import glob
import json
import pathlib
import random
import re
import sys
from collections import defaultdict

import yaml

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))

from src.corpusaudit.db import open_corpus  # noqa: E402

GUIDELINES = """\
# Slovak FineWeb2 audit: annotation guidelines

You will see documents drawn from a corpus that a curation pipeline labelled as
**Slovak** and shipped as pretraining data. Documents are shown in random
order; the sampling method and the reason a document was selected are
deliberately hidden from you.

For each document give **two** labels.

## 1. Language

* `sk`      Slovak. Normal Slovak text. Informal, diacritic-free or
            misspelled Slovak still counts as Slovak.
* `sk-pred` Predominantly Slovak: mostly Slovak, but with a non-trivial
            amount of another language (e.g. a Czech or English block).
* `cs`      Czech. The document is essentially Czech.
* `mix`     Mixed Slovak/Czech: substantial amounts of both, neither clearly
            dominant.
* `other`   Some other language, or genuinely multilingual beyond sk/cs.
* `?`       Uncertain.

## 2. Usefulness as Slovak corpus text

* `good`    Useful natural text: coherent prose a person wrote (or a decent
            translation) that you would keep in a Slovak corpus.
* `noisy`   Usable but noisy: real content mixed with menus, repetition,
            formatting debris, or awkward machine translation.
* `junk`    Boilerplate, template, navigation, listing spam, keyword salad,
            incoherent machine-generated text, or otherwise not usable.
* `?`       Uncertain.

Readability is not the test. Fluent, correctly spelled Slovak is still `junk`
when the page exists to place links, keywords or advertising rather than to say
something: doorway pages, tag and category listings, autogenerated product,
crypto or gambling copy. `noisy` is for real content with debris around it, not
for debris that happens to be readable.

Judge only what you see. If the excerpt is truncated, judge the excerpt.
"""

UUID = re.compile(r"<urn:uuid:[0-9a-f-]+>")


def inspected_ids(runs: list[str]) -> set[str]:
    seen: set[str] = set()
    for run in runs:
        path = pathlib.Path(run) / "tools.jsonl"
        if not path.exists():
            continue
        for line in path.read_text().splitlines():
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                continue
            seen.update(UUID.findall(rec.get("result", "")))
    return seen


def collect(runs: list[str], per_agent: int, per_baseline: int,
            max_per_strategy: int) -> list[tuple[str, str, str, int]]:
    """Return (source, slice_id, selector, n_items), selectors deduplicated."""
    by_selector: dict[str, dict] = {}
    for run in runs:
        for path in sorted(glob.glob(f"{run}/findings/*.yaml")):
            t = yaml.safe_load(open(path))
            sel = t["selector"].strip()
            entry = by_selector.setdefault(
                sel, {"source": "agent", "id": t["id"], "runs": []})
            entry["runs"].append(pathlib.Path(run).name)
    per_strategy: dict[str, int] = defaultdict(int)
    for path in sorted(glob.glob("out/baselines/*/findings/*.yaml")):
        t = yaml.safe_load(open(path))
        ev = t.get("evidence", {})
        if ev.get("selector_error") or not ev.get("n_matched"):
            continue
        strategy = pathlib.Path(path).parent.parent.name
        if per_strategy[strategy] >= max_per_strategy:
            continue
        sel = t["selector"].strip()
        if sel in by_selector:  # identical to an agent selector; already covered
            continue
        per_strategy[strategy] += 1
        by_selector[sel] = {"source": f"baseline:{strategy}", "id": t["id"], "runs": []}

    out = []
    for sel, meta in by_selector.items():
        n = per_agent if meta["source"] == "agent" else per_baseline
        out.append((meta["source"], meta["id"], sel, n))
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", nargs="*",
                    default=["out/runs/main", "out/runs/rep1", "out/runs/rep2"])
    ap.add_argument("--per-agent-slice", type=int, default=25)
    ap.add_argument("--per-baseline-slice", type=int, default=12)
    ap.add_argument("--max-per-strategy", type=int, default=3)
    ap.add_argument("--control", type=int, default=40)
    ap.add_argument("--max-chars", type=int, default=1800)
    ap.add_argument("--derived", default="data/derived")
    ap.add_argument("--out", default="out/annotation")
    ap.add_argument("--seed", type=int, default=20260814)
    ap.add_argument("--force", action="store_true",
                    help="rebuild even if judgments already exist (orphans them)")
    args = ap.parse_args()

    out = pathlib.Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    # Regenerating would renumber item ids and orphan any labels already given.
    labels = out / "labels.csv"
    if labels.exists() and len(labels.read_text().splitlines()) > 1 and not args.force:
        print(f"{labels} already holds "
              f"{len(labels.read_text().splitlines()) - 1} judgments; refusing to "
              "rebuild the package and orphan them. Pass --force to override.")
        return 0
    corpus = open_corpus(args.derived)

    seen = inspected_ids(args.runs)
    print(f"excluding {len(seen)} documents already inspected by the agent")

    slices = collect(args.runs, args.per_agent_slice, args.per_baseline_slice,
                     args.max_per_strategy)
    slices.append(("control", "random_control", "true", args.control))

    items: list[dict] = []
    chosen: set[str] = set()
    for source, sid, selector, n in slices:
        try:
            rows = corpus.con.execute(
                f"select id, substr(text, 1, {args.max_chars}) from docs "
                f"where ({selector}) order by hash(id || 'annot') limit {n * 5}"
            ).fetchall()
        except Exception as exc:
            print(f"  ! {sid}: {exc}")
            continue
        picked = 0
        for doc_id, text in rows:
            if picked >= n:
                break
            if doc_id in seen or doc_id in chosen or not text:
                continue
            chosen.add(doc_id)
            items.append({"doc_id": doc_id, "text": text, "slice": sid, "source": source})
            picked += 1
        print(f"{source:>20} / {sid:<46} {picked:>3d}")

    random.Random(args.seed).shuffle(items)
    for i, it in enumerate(items, 1):
        it["item_id"] = f"A{i:04d}"

    with open(out / "items.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["item_id", "text"])
        w.writeheader()
        w.writerows({"item_id": it["item_id"], "text": it["text"]} for it in items)
    with open(out / "provenance.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["item_id", "doc_id", "slice", "source"])
        w.writeheader()
        w.writerows({k: it[k] for k in ("item_id", "doc_id", "slice", "source")} for it in items)
    (out / "GUIDELINES.md").write_text(GUIDELINES)
    print(f"\n{len(items)} items -> {out}/items.csv")
    print("annotate with:  uv run python scripts/annotate.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
